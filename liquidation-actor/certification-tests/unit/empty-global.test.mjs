import fs from 'node:fs';
import assert from 'node:assert/strict';
import { parseSearchPage } from '../../src/liquidation/parser.js';
import { emptyGlobalCategoryFallback } from '../../src/liquidation/discovery.js';
import { evaluateRunHealth } from '../../src/liquidation/health.js';
const url = 'https://www.liquidation.com/auction/search?flag=new';
const html = fs.readFileSync(new URL('../fixtures/liquidation-empty-global-live.html', import.meta.url), 'utf8');
const parsed = parseSearchPage(html, url);
assert.equal(parsed.items.length, 0);
assert.equal(parsed.explicitEmpty, true);
assert.equal(parsed.resultCount, 0);
const next = emptyGlobalCategoryFallback(parsed, url);
assert.equal(next.length, 3);
assert.equal(new Set(next.map(value => new URL(value).searchParams.get('searchparam_category1'))).size, 3);
assert.ok(next.every(value => parsed.discoveryLinks.some(link => link.url === value)));
assert.deepEqual(emptyGlobalCategoryFallback(parsed, url + '&searchparam_words=laptop'), []);
assert.deepEqual(emptyGlobalCategoryFallback(parsed, url, 'laptop'), []);
assert.deepEqual(emptyGlobalCategoryFallback(parsed, url + '&searchparam_seller=example'), []);
assert.deepEqual(emptyGlobalCategoryFallback({ ...parsed, items: [{}] }, url), []);
const result = evaluateRunHealth({ discovery_requests: 1, records_discovered: 0, records_saved: 0, duplicates_skipped: 0 }, { discoveryMode: 'TARGETED' });
assert.equal(result.status, 'FAIL');
assert.ok(result.reasons.includes('no_listings_discovered_for_ingestion'));
assert.equal(evaluateRunHealth({ discovery_requests: 1, records_discovered: 10, records_saved: 0, duplicates_skipped: 10 }, { discoveryMode: 'TARGETED' }).status, 'PASS');
console.log('PASS exact live zero-result page, bounded observed-category fallback, filter preservation, and no false successful empty ingestion');