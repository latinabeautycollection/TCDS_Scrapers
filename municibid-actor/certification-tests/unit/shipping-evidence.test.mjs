import assert from 'node:assert/strict';
import { load } from 'cheerio';
import { classifyShipping } from '../../src/municibid/shippingEvidence.js';
import { productFields } from '../../src/municibid/productFields.js';
import { computeContentHash } from '../../src/municibid/fieldRules.js';
const pickup = classifyShipping({ answer: 'No. Pickup only.' });
assert.equal(pickup.shipping_method, 'pickup_only');
assert.equal(pickup.shipping_evidence, 'Pickup only.');
assert.equal(pickup.estimated_shipping, null);
assert.equal(classifyShipping({ title: 'FREE SHIPPING USA ONLY' }).shipping_method, 'free_shipping');
assert.equal(classifyShipping({ title: 'FREE SHIPPING USA ONLY' }).estimated_shipping, 0);
assert.equal(classifyShipping({ cost: 25, costText: 'Shipping Cost: $25.00' }).shipping_method, 'shipping');
assert.equal(classifyShipping({ answer: 'Yes' }).shipping_method, 'shipping_quote');
assert.equal(classifyShipping({ description: 'Seller ships. Contact seller for a quote.' }).estimated_shipping, null);
assert.equal(classifyShipping({ title: 'FREE SHIPPING', terms: 'No shipping. Must be picked up.' }).shipping_method, 'pickup_only');
assert.equal(classifyShipping({ description: 'Chemical delivery system. Ship loose items.' }).shipping_method, null);
assert.equal(classifyShipping({ description: 'No shipping damage. Shipping is available.' }).shipping_method, 'shipping_quote');
assert.equal(productFields(load(''), 'Rear Driver Handles and Locks Inoperable').condition, 'Rear Driver Handles and Locks Inoperable');
assert.match(productFields(load(''), 'There is no know issues with the vehicle. This vehicle is patrol ready.').condition, /no know issues/);
assert.equal(productFields(load(''), 'Door panel options and emergency lighting.').condition, null);
assert.notEqual(computeContentHash({ shipping_method: 'pickup_only' }), computeContentHash(pickup));
console.log('PASS sourced condition, pickup evidence, shipping price/quote/free rules, negative precedence, false-positive exclusions, correction hashing');